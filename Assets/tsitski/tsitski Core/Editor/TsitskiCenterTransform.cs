using System.Collections.Generic;
using System.Linq;
using UnityEditor;
using UnityEngine;
using Object = UnityEngine.Object;

namespace Tsitski.Core {
    public interface ICenterTransformHook {
        bool TryGetLocalBounds(GameObject gameObject, out Bounds bounds);
        IEnumerable<Transform> KeepLocal(GameObject gameObject);
        void Moved(GameObject gameObject, Vector3 offset, bool handledByGenerator);
    }

    public static class TsitskiCenterTransform {
        private const string MenuPath = "Tools/tsitski/Core/Center Transform To Mesh";
        private const string UndoName = "Center Transform To Mesh";
        private static readonly List<ICenterTransformHook> Hooks = new();

        public static void Register(ICenterTransformHook hook) {
            if (!Hooks.Contains(hook))
                Hooks.Add(hook);
        }

        [MenuItem(MenuPath, false, 201)]
        private static void CenterSelected() {
            Undo.IncrementCurrentGroup();
            Undo.SetCurrentGroupName(UndoName);
            int group = Undo.GetCurrentGroup();

            foreach (GameObject gameObject in Selection.gameObjects)
                Center(gameObject);

            Undo.CollapseUndoOperations(group);
            SceneView.RepaintAll();
        }

        [MenuItem(MenuPath, true)]
        private static bool CenterSelectedValidate() => Selection.gameObjects.Length > 0;

        public static bool Center(GameObject gameObject) {
            if (!CanCenter(gameObject, out IPivotShiftable[] shiftables, out string reason)) {
                Debug.LogWarning($"[tsitski] {UndoName} skipped '{gameObject.name}': {reason}", gameObject);
                return false;
            }

            if (!TryGetLocalBounds(gameObject, out Bounds bounds)) {
                Debug.LogWarning($"[tsitski] {UndoName} skipped '{gameObject.name}': it has no mesh to center on.", gameObject);
                return false;
            }

            Transform transform = gameObject.transform;
            Vector3 center = SnapToGrid(transform.TransformPoint(bounds.center));
            Vector3 offset = transform.InverseTransformPoint(center);
            if (offset.sqrMagnitude < 1e-10f)
                return false;

            HashSet<Transform> keepLocal = new(Hooks.SelectMany(h => h.KeepLocal(gameObject)).Where(t => t));
            Transform[] children = transform.Cast<Transform>().Where(c => !keepLocal.Contains(c)).ToArray();
            (Vector3 position, Quaternion rotation)[] poses = children.Select(c => (c.position, c.rotation)).ToArray();

            Undo.RecordObject(transform, UndoName);
            Undo.RecordObjects(children.Cast<Object>().Concat(keepLocal).ToArray(), UndoName);
            Undo.RecordObjects(shiftables.Cast<Object>().ToArray(), UndoName);

            transform.position = center;
            for (int i = 0; i < children.Length; i++)
                children[i].SetPositionAndRotation(poses[i].position, poses[i].rotation);

            foreach (IPivotShiftable shiftable in shiftables)
                shiftable.ShiftLocalPoints(-offset);

            foreach (ICenterTransformHook hook in Hooks)
                hook.Moved(gameObject, -offset, shiftables.Length > 0);

            foreach (IPivotShiftable shiftable in shiftables) {
                shiftable.ApplyPivotShift();
                EditorUtility.SetDirty((Object)shiftable);
            }

            return true;
        }

        private static bool CanCenter(GameObject gameObject, out IPivotShiftable[] shiftables, out string reason) {
            shiftables = gameObject.GetComponents<IPivotShiftable>();
            reason = null;

            foreach (IGenerated generated in gameObject.GetComponents<IGenerated>())
                if (generated.generator) {
                    reason = $"it is generated by '{generated.generator.name}', center that object instead.";
                    return false;
                }

            foreach (IPivotShiftable shiftable in shiftables)
                if (!shiftable.CanShiftPivot(out reason))
                    return false;

            foreach (MonoBehaviour behaviour in gameObject.GetComponents<MonoBehaviour>())
                if (behaviour is (IInputHashed or IGenerated or IPathOwner or ITsitskiPath) and not IPivotShiftable) {
                    reason = $"its {behaviour.GetType().Name} can't keep its points in place when the pivot moves.";
                    return false;
                }

            return true;
        }

        private static bool TryGetLocalBounds(GameObject gameObject, out Bounds bounds) {
            foreach (ICenterTransformHook hook in Hooks)
                if (hook.TryGetLocalBounds(gameObject, out bounds))
                    return true;

            bounds = default;
            if (!gameObject.TryGetComponent(out MeshFilter filter) || !filter.sharedMesh || filter.sharedMesh.vertexCount == 0)
                return false;

            bounds = filter.sharedMesh.bounds;
            return true;
        }

        private static Vector3 SnapToGrid(Vector3 position) {
#if UNITY_2022_2_OR_NEWER
            Vector3 grid = EditorSnapSettings.gridSize;
#else
            Vector3 grid = EditorSnapSettings.move;
#endif
            for (int axis = 0; axis < 3; axis++)
                if (grid[axis] > 1e-5f)
                    position[axis] = Mathf.Round(position[axis] / grid[axis]) * grid[axis];
            return position;
        }
    }
}
